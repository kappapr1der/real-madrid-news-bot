def clean_text(text: str) -> str:
    text = unescape(text)

    # Базовые замены
    replacements = {
        # Футбол
        "в Реал -Мадриде": "в «Реале»",
        "Реал Мадрид": "«Реал»",
        "Барселона": "«Барселона»",
        "Манчестер Юнайтед": "«Манчестер Юнайтед»",
        "Арсенал": "«Арсенал»",
        "Ливерпуль": "«Ливерпуль»",

        # Типичные кривые переводы
        "смотрит, чтобы продолжить": "продолжит",
        "отвечает на то, что": "о",
        "остаются в статиле": "застопорились",
        "со своего лунного шара": "лунного удара",
        "источник сообщил": "источник рассказал",
        "взвешивает прогресс": "оценил прогресс",

        # Чистим повторы
        "предложение по контракту": "контракт",
    }

    replacements.update({
        "Фабрицио Романо подтверждает, что у Флорентино Переса есть список из 5 полузащитников, которых нужно подписать в ближайшие месяцы: «Один из них-Энцо Фернандес»": "Фабрицио Романо: у Флорентино есть список из пяти полузащитников. Один из них - Энцо Фернандес",
        "Один из них-Энцо": "Один из них - Энцо",
        "Фабрицио Романо объявил о подписании контракта с «Реалом» еще одним элитным свободным агентом": "Фабрицио Романо сообщил о ещё одном свободном агенте для «Реала»",
        "Фабрицио Романо объявил о подписании контракта с мадридским «Реалом» еще одним элитным свободным агентом": "Фабрицио Романо сообщил о ещё одном свободном агенте для «Реала»",
        "Ожидается новое подписание контракта с «Реалом», в то время как готовится отъезд": "У «Реала» на подходе новичок, параллельно готовится уход",
        "Ожидается новое подписание контракта с мадридским «Реалом», в то время как готовится отъезд": "У «Реала» на подходе новичок, параллельно готовится уход",
        "Удар по столу, который Бавария намерена нанести Олисе, чтобы остановить Мадрид": "«Бавария» готовит ход по Олисе, чтобы остановить интерес «Реала»",
    })

    for bad, good in replacements.items():
        text = text.replace(bad, good)

    # Приводим все формы с "Реалом" к кавычкам
    forms = {
        r"^Реал\b": "«Реал»",
        r"\bв Реале\b": "в «Реале»",
        r"\bиз Реала\b": "из «Реала»",
        r"\bо Реале\b": "о «Реале»",
        r"\bдля Реала\b": "для «Реала»",
        r"\bк Реалу\b": "к «Реалу»",
        r"\bс Реалом\b": "с «Реалом»",
        r"\bпротив Реала\b": "против «Реала»",
        r"\bнад Реалом\b": "над «Реалом»",
        r"\bу Реала\b": "у «Реала»",
        r"\bпо Реалу\b": "по «Реалу»",
    }
    for pattern, repl in forms.items():
        text = re.sub(pattern, repl, text)

    # Чистим мусорные хвосты
    text = re.sub(r"\s*\(?(VIDEO|ФОТО|Фото|ВИДЕО)\)?", "", text, flags=re.IGNORECASE)
    text = re.sub(r"\s*\[LIVE\]", "", text, flags=re.IGNORECASE)
    text = re.sub(r"\s*[-–—]\s*подробности.*$", "", text, flags=re.IGNORECASE)

    # Убираем повторы слов подряд ("Реал Реал" -> "Реал")
    text = re.sub(r"\b(\w+)( \1\b)+", r"\1", text, flags=re.IGNORECASE)

    text = _fix_russian_quotes(text)
    text = _apply_editorial_rewrites(text)
    text = _fix_russian_quotes(text)
    text = text.replace("» Реала»", "«Реала»")
    text = re.sub(r"(\d+),\s+(\d+)", r"\1,\2", text)

    # Убираем эмодзи (любые юникодные пиктограммы)
    emoji_pattern = re.compile(
        "["
        "\U0001F600-\U0001F64F"
        "\U0001F300-\U0001F5FF"
        "\U0001F680-\U0001F6FF"
        "\U0001F1E0-\U0001F1FF"
        "\U00002700-\U000027BF"
        "\U0001F900-\U0001F9FF"
        "\U00002600-\U000026FF"
        "]+",
        flags=re.UNICODE,
    )
    text = emoji_pattern.sub("", text)

    # Чистим лишние пробелы и переносы
    text = re.sub(r"\s+", " ", text).strip()

    # Ограничиваем длину текста (по символам) после редакторской чистки.
    max_len = 180
    if len(text) > max_len:
        cut = text[:max_len].rsplit(" ", 1)[0]
        text = cut + "…"

    # fallback-маркер: если видим подозрительное
    bad_markers = ["смотрит,", "в статиле", "со своего", "блокбастер", "CB", "Таргетом", "Аутсайдера"]
    if any(marker in text for marker in bad_markers):
        return text + " (англ.)"

    return text
